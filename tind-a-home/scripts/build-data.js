// Builds js/data.js from the Find-A-Home data folder (../find-a-home/data).
// Run from the tind-a-home folder:  node scripts/build-data.js
// data.js is loaded as a plain <script>, so index.html works when opened directly (no server needed).
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', '..', 'find-a-home', 'data');
const OUT = path.join(__dirname, '..', 'js', 'data.js');
const read = f => JSON.parse(fs.readFileSync(f, 'utf8'));
const titles = read(path.join(SRC, 'reference', 'citation-titles.json'));
const KEEP_Q = ['481', '410', '479', '452', '404', '408'];

const homes = fs.readdirSync(path.join(SRC, 'facilities'))
  .filter(f => f.endsWith('.json'))
  .map(f => read(path.join(SRC, 'facilities', f)))
  .map(p => {
    const ins = p.inspections || [];
    const latest = ins.filter(i => i.cycle === 1);
    return {
      id: p.id, type: p.type, name: p.name, aka: p.aka || null,
      city: p.city, area: p.area, address: p.address, zip: p.zip, phone: p.phone,
      lat: p.lat, lon: p.lon, website: p.website, careCompare: p.careCompare || null,
      priceLow: p.priceLow, priceHigh: p.priceHigh, priceEstimated: !!p.priceEstimated, priceNote: p.priceNote,
      rating: p.rating, memoryCare: p.memoryCare, memoryUnits: p.memoryUnits, beds: p.beds,
      openings: p.openings, payment: p.payment, behavioral: !!p.behavioral, bio: p.bio,
      cms: p.cms ? {
        overall: p.cms.overall, inspection: p.cms.inspection, staffing: p.cms.staffing, quality: p.cms.quality,
        nurseHours: p.cms.nurseHours, rnHours: p.cms.rnHours, turnover: p.cms.turnover,
        deficiencies: p.cms.deficiencies, complaintDeficiencies: p.cms.complaintDeficiencies,
        inspectionDate: p.cms.inspectionDate, fines: p.cms.fines, fineDollars: p.cms.fineDollars,
        abuse: p.cms.abuse, sff: p.cms.sff, sffCandidate: p.cms.sffCandidate, ownership: p.cms.ownership,
        familyCouncil: p.cms.familyCouncil
      } : null,
      quality: (p.quality || []).filter(q => KEEP_Q.includes(q.code)),
      recentHarm: latest.some(i => i.level === 3),
      recentJeopardy: latest.some(i => i.level === 4),
      citations: latest.slice(0, 6).map(i => ({
        title: i.title || titles.titles[i.tag] || 'Citation', sev: i.level, date: i.date,
        dementia: !!i.dementia, complaint: !!i.complaint, corrected: !!i.corrected
      })),
      sources: p.sources
    };
  });

const zips = read(path.join(SRC, 'reference', 'zips.json'));
const averages = read(path.join(SRC, 'reference', 'averages.json'));
const out = `// Generated by scripts/build-data.js from ../find-a-home/data. Do not edit by hand.\n` +
  `window.TAH_DATA = ${JSON.stringify({ homes, zips, averages })};\n`;
fs.writeFileSync(OUT, out);
console.log(`Wrote ${homes.length} homes and ${Object.keys(zips).length} ZIPs to ${OUT} (${(out.length / 1024).toFixed(0)} KB)`);
