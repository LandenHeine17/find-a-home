// Builds js/data.js from the Find-A-Home data folder (../find-a-home/data).
// Run: node scripts/build-data.js
// The site loads data.js as a normal <script>, so index.html works when opened directly (no server needed).
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', '..', 'find-a-home', 'data');
const OUT = path.join(__dirname, '..', 'js', 'data.js');
const read = f => JSON.parse(fs.readFileSync(f, 'utf8'));

const facilities = fs.readdirSync(path.join(SRC, 'facilities'))
  .filter(f => f.endsWith('.json'))
  .map(f => read(path.join(SRC, 'facilities', f)))
  .map(p => {
    const ins = p.inspections || [];
    const latest = ins.filter(i => i.cycle === 1);
    return {
      id: p.id, type: p.type, name: p.name, aka: p.aka || null,
      city: p.city, address: p.address, zip: p.zip, phone: p.phone,
      lat: p.lat, lon: p.lon, website: p.website, careCompare: p.careCompare || null,
      priceLow: p.priceLow, priceHigh: p.priceHigh, priceEstimated: p.priceEstimated, priceNote: p.priceNote,
      rating: p.rating, memoryCare: p.memoryCare, memoryUnits: p.memoryUnits, beds: p.beds,
      openings: p.openings, payment: p.payment, behavioral: !!p.behavioral, bio: p.bio,
      cms: p.cms ? {
        overall: p.cms.overall, inspection: p.cms.inspection, staffing: p.cms.staffing, quality: p.cms.quality,
        nurseHours: p.cms.nurseHours, turnover: p.cms.turnover, deficiencies: p.cms.deficiencies,
        inspectionDate: p.cms.inspectionDate, fines: p.cms.fines, abuse: p.cms.abuse,
        sff: p.cms.sff, sffCandidate: p.cms.sffCandidate, ownership: p.cms.ownership
      } : null,
      quality: (p.quality || []).filter(q => ['481', '410', '479'].includes(q.code)),
      recentHarm: latest.some(i => i.level === 3),
      recentJeopardy: latest.some(i => i.level === 4),
      citations: latest.slice(0, 4).map(i => ({ title: i.title, sev: i.level, date: i.date })),
      sources: p.sources
    };
  });

const zips = read(path.join(SRC, 'reference', 'zips.json'));
const out = `// Generated by scripts/build-data.js from ../find-a-home/data — do not edit by hand.\n` +
  `window.MAH_DATA = ${JSON.stringify({ facilities, zips })};\n`;
fs.writeFileSync(OUT, out);
console.log(`Wrote ${facilities.length} facilities and ${Object.keys(zips).length} ZIPs to ${OUT} (${(out.length / 1024).toFixed(0)} KB)`);
